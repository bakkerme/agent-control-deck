import { test, expect, _electron as electron } from "@playwright/test";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { randomUUID } from "node:crypto";

test("create a custom project from the final dropdown item and retain the permanent repo grouping", async () => {
  const dir = mkdtempSync(join(tmpdir(), "acd-projects-"));
  const env = Object.fromEntries(Object.entries(process.env).filter(([key, value]) => key !== "ELECTRON_RUN_AS_NODE" && value !== undefined)) as Record<string, string>;
  const launch = () => electron.launch({ executablePath: process.env.ACD_PACKAGED_EXECUTABLE, args: [...(process.env.ACD_PACKAGED_EXECUTABLE ? [] : [resolve(".")]), `--data-dir=${dir}`], env: { ...env, ACD_HTTP_PORT: "0" } });
  let app = await launch();
  try {
    let page = await app.firstWindow();
    const initial = await page.evaluate(() => window.deck.command({ type: "createSource", name: "Local Claude", provider: "claude", environment: "native" }));
    const source = initial.sources[0];
    const emit = (session: string, prompt: string) => writeFileSync(join(initial.setups[source.id].inbox, `${randomUUID()}.json`), JSON.stringify({ version: 1, eventId: randomUUID(), payload: { hook_event_name: "UserPromptSubmit", session_id: session, cwd: "/work/repo-fixture", prompt } }));
    emit("first", "First repo task");
    await page.getByRole("button", { name: "Select chat First repo task", exact: true }).click();
    const organization = page.getByRole("region", { name: "Chat organization" });
    const selector = organization.getByRole("combobox", { name: "Additional project", exact: true });
    await expect(organization.getByText("Repository project · permanent", { exact: true })).toBeVisible();
    await expect(organization.getByRole("button", { name: "Rename project", exact: true })).toHaveCount(0);
    await expect(selector.locator("option").last()).toHaveText("Add a new project");
    await selector.selectOption("add-project");
    await page.getByRole("dialog").getByLabel("Project name", { exact: true }).fill("Release planning");
    await page.getByRole("dialog").getByRole("button", { name: "Create project", exact: true }).click();
    const snapshot = await page.evaluate(() => window.deck.load());
    const custom = snapshot.projects.find(p => p.name === "Release planning")!;
    const repo = snapshot.projects.find(p => p.name === "repo-fixture")!;
    await expect(selector).toHaveValue(custom.id);
    await expect(page.getByRole("button", { name: /^Release planning 1$/ })).toHaveClass("selected");
    await expect(page.getByRole("button", { name: /^repo-fixture 1$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: "Select chat First repo task", exact: true })).toBeVisible();
    await page.getByRole("button", { name: /^repo-fixture 1$/ }).click();
    await expect(page.locator(".projects").getByRole("button", { name: "Rename project", exact: true })).toHaveCount(0);
    await selector.selectOption("");
    await expect(page.getByRole("status")).toHaveText("Saved");
    await expect(page.getByRole("button", { name: /^Release planning 0$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: "Select chat First repo task", exact: true })).toBeVisible();
    await selector.selectOption(custom.id);
    await expect(page.getByRole("status")).toHaveText("Saved");
    emit("second", "New repo task");
    await expect(page.getByRole("button", { name: /^repo-fixture 2$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: /^Release planning 1$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: "Select chat New repo task", exact: true })).toBeVisible();
    await page.screenshot({ path: "test-results/repository-projects.png" });
    await organization.getByRole("button", { name: "Archive chat", exact: true }).click();
    await expect(page.getByRole("button", { name: /^repo-fixture 1$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: /^Release planning 0$/ })).toBeVisible();
    await page.getByRole("button", { name: /^Archived chats 1$/ }).click();
    await expect(page.getByRole("button", { name: /^repo-fixture 1$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: /^Release planning 1$/ })).toBeVisible();
    await expect(page.getByRole("button", { name: "Select chat First repo task", exact: true })).toBeVisible();
    await organization.getByRole("button", { name: "Restore chat", exact: true }).click();
    await expect(page.getByRole("button", { name: /^repo-fixture 2$/ })).toBeVisible();
    await app.close();
    app = await launch(); page = await app.firstWindow();
    await page.getByRole("button", { name: /^Release planning 1$/ }).click();
    await page.getByRole("button", { name: "Select chat First repo task", exact: true }).click();
    await expect(page.getByRole("combobox", { name: "Additional project", exact: true })).toHaveValue(custom.id);
    const saved = (await page.evaluate(() => window.deck.load())).chats.find(c => c.externalId === "first")!;
    expect(saved.repoProjectId).toBe(repo.id);
    expect(saved.projectId).toBe(custom.id);
  } finally { await app.close(); rmSync(dir, { recursive: true, force: true }); }
});
